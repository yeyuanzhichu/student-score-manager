-- 班级学生成绩管理系统 - H2 数据库结构
-- 由 DatabaseInitializer 在应用启动时自动执行

CREATE TABLE IF NOT EXISTS users (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(50)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('TEACHER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS classes (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name VARCHAR(60) NOT NULL,
    grade_year INT         NOT NULL,
    major      VARCHAR(80) NOT NULL,
    advisor    VARCHAR(50),
    CONSTRAINT uk_classes_name UNIQUE (class_name)
);

CREATE TABLE IF NOT EXISTS students (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_no    VARCHAR(20)  NOT NULL,
    name          VARCHAR(50)  NOT NULL,
    gender        VARCHAR(10)  NOT NULL DEFAULT '男',
    class_id      INT          NOT NULL,
    phone         VARCHAR(20),
    password_hash VARCHAR(100) NOT NULL,
    status        TINYINT      NOT NULL DEFAULT 1,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_students_no UNIQUE (student_no),
    CONSTRAINT fk_students_class FOREIGN KEY (class_id) REFERENCES classes (id),
    CONSTRAINT ck_students_gender CHECK (gender IN ('男', '女')),
    CONSTRAINT ck_students_status CHECK (status IN (0, 1))
);

CREATE TABLE IF NOT EXISTS courses (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code  VARCHAR(20)  NOT NULL,
    course_name  VARCHAR(80)  NOT NULL,
    credit       DECIMAL(3,1) NOT NULL,
    teacher_name VARCHAR(50)  NOT NULL,
    semester     VARCHAR(30)  NOT NULL,
    CONSTRAINT uk_courses_code UNIQUE (course_code),
    CONSTRAINT ck_courses_credit CHECK (credit > 0 AND credit <= 20)
);

CREATE TABLE IF NOT EXISTS scores (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INT          NOT NULL,
    course_id  INT          NOT NULL,
    score      DECIMAL(4,1) NOT NULL,
    entered_by INT,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_scores_student_course UNIQUE (student_id, course_id),
    CONSTRAINT fk_scores_student FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
    CONSTRAINT fk_scores_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_scores_user FOREIGN KEY (entered_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_scores_value CHECK (score >= 0 AND score <= 100)
);

CREATE INDEX IF NOT EXISTS idx_students_class ON students (class_id);
CREATE INDEX IF NOT EXISTS idx_scores_course ON scores (course_id);
CREATE INDEX IF NOT EXISTS idx_scores_student ON scores (student_id);
